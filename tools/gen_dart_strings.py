#!/usr/bin/env python3
"""Copy the bot's messages into the Flutter app so both say exactly the same thing.

Run from the repo root after editing services/api/app/i18n.py:
    python tools/gen_dart_strings.py
Only keys that make sense in the app are copied (the rest mention WhatsApp commands like BRIEF).
"""

import json
import pathlib
import sys

sys.path.insert(0, "services/api")
from app.i18n import MESSAGES  # noqa: E402

KEYS = ["line_basis_personal", "line_basis_default", "plan_head", "plan_steps", "late", "wrong_ack", "status",
        "status_unknown", "export_head"]
LANGS = ["en", "hi", "kn", "te", "ta"]


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


out = ["// GENERATED by tools/gen_dart_strings.py from services/api/app/i18n.py. Do not edit by hand.",
       "// Hindi, Kannada, Telugu and Tamil are DRAFT: native-speaker and clinical review required.",
       "const Map<String, Map<String, String>> botStrings = {"]
for k in KEYS:
    out.append(f"  '{k}': {{")
    for lang in LANGS:
        out.append(f"    '{lang}': {lit(MESSAGES[k][lang])},")
    out.append("  },")
out.append("};")
pathlib.Path("apps/mobile/lib/l10n/bot_strings.g.dart").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote apps/mobile/lib/l10n/bot_strings.g.dart")
